import assert from 'node:assert/strict';
import { defaultHomeTools, groupHomeTools, HOME_TOOL_IDS, HOME_TOOLS_KEY, parseHomeTools, readHomeTools, saveHomeTools } from '../src/lib/homeTools.ts';
let raw = null;
const storage = { getItem: () => raw, setItem: (key, value) => { assert.equal(key, HOME_TOOLS_KEY); raw = value; } };
const defaults = defaultHomeTools(), groups = groupHomeTools(defaults, false);
assert.equal(groups.primary.length, 6);
assert.equal(new Set([...groups.primary, ...groups.more]).size, HOME_TOOL_IDS.length);
assert.deepEqual(groupHomeTools(defaults, true).primary, defaults.tools.filter(item => item.pinned).map(item => item.id));
const configured = { ...defaults, tools: defaults.tools.map(item => item.id === 'game' ? { ...item, visible: false } : item).reverse() };
const value = saveHomeTools(configured, null, storage);
assert.equal(value, raw); assert.deepEqual(readHomeTools(storage).config, configured);
assert.equal([...groupHomeTools(configured, false).primary, ...groupHomeTools(configured, false).more].includes('game'), false);
assert.throws(() => saveHomeTools(defaults, null, storage), /另一页面/);
assert.throws(() => parseHomeTools({ version: 1, tools: [defaults.tools[0], defaults.tools[0]] }), /重复/);
raw = '{bad'; assert.ok(readHomeTools(storage).error); assert.equal(raw, '{bad');
assert.throws(() => saveHomeTools(defaults, raw, { getItem: storage.getItem, setItem: () => { throw Error('quota'); } }), /quota/);
assert.equal(raw, '{bad');
assert.equal(parseHomeTools({ version: 1, tools: [] }).tools.length, HOME_TOOL_IDS.length);
console.log('Homepage tool preference order, pin, hiding, compact mode and CAS: PASS');
