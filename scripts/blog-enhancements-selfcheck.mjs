import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
import { planBlogMerge, resolveBlogMerge } from '../src/lib/blogMerge.ts';
import { inspectBlogImage, uploadBlogImage, BLOG_IMAGE_MAX_BYTES } from '../src/services/blogImages.ts';
globalThis.crypto ||= webcrypto;
const merge = (base, local, remote, choices = {}) => resolveBlogMerge(planBlogMerge(base, local, remote), choices);
assert.equal(merge('a\n\nb\n\nc\n', 'A\n\nb\n\nc\n', 'a\n\nb\n\nC\n'), 'A\n\nb\n\nC\n');
assert.equal(merge('a\nb\n', 'A\nb\n', 'a\nB\n'), 'A\nB\n');
assert.equal(merge('a\nb\n', 'a\n', 'a\nb\nc\n'), 'a\nc\n');
assert.equal(merge('', 'new', ''), 'new');
assert.equal(merge('a', '', ''), '');
assert.equal(merge('a\n', 'a\none\n', 'a\ntwo\n'), null);
const plan = planBlogMerge('a\n\nb\n', 'a\n\nlocal\n', 'a\n\nremote\n');
const conflict = plan.blocks.find(block => block.merged === null);
assert.ok(conflict);
assert.equal(resolveBlogMerge(plan, { [conflict.id]: 'local' }), 'a\n\nlocal\n');
assert.equal(resolveBlogMerge(plan, { [conflict.id]: 'remote' }), 'a\n\nremote\n');
assert.equal(merge('same', 'same', 'same'), 'same');
const raw = '\uFEFF---\r\ntitle: "t"\r\ncustom:\r\n  nested: true\r\n---\r\n\r\nold\r\nend\r\n';
const local = raw.replace('old', 'mine'), remote = raw.replace('true', 'false');
assert.equal(merge(raw, local, remote), raw.replace('true', 'false').replace('old', 'mine'));
for (let n = 1; n <= 80; n++) {
  const base = Array.from({ length: n }, (_, i) => 'line-' + i + '\n').join('');
  const next = base.replace('line-0', 'edited') + 'added\n';
  assert.equal(merge(base, next, base), next);
  assert.equal(merge(base, base, next), next);
  assert.equal(merge(base, next, next), next);
}
const big = Array.from({ length: 1700 }, (_, i) => 'old-' + i + '\n').join('');
const changed = Array.from({ length: 1700 }, (_, i) => 'new-' + i + '\n').join('');
assert.ok(planBlogMerge(big, changed, big).fallback);
assert.equal(merge(big, changed, big), changed);
assert.throws(() => planBlogMerge('', 'x'.repeat(262145), ''), /256 KB/);
assert.throws(() => merge('base\n', 'x'.repeat(160000) + '\nbase\n', 'base\n' + 'y'.repeat(160000)), /合并结果超过/);
const png = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10, 0]);
assert.equal(inspectBlogImage(png).extension, 'png');
assert.equal(inspectBlogImage(new Uint8Array([255, 216, 255, 1])).mime, 'image/jpeg');
assert.equal(inspectBlogImage(new TextEncoder().encode('GIF89a___')).extension, 'gif');
assert.equal(inspectBlogImage(new TextEncoder().encode('RIFF____WEBP___')).extension, 'webp');
assert.throws(() => inspectBlogImage(new TextEncoder().encode('<svg/>')), /仅支持/);
assert.throws(() => inspectBlogImage(new Uint8Array(BLOG_IMAGE_MAX_BYTES + 1)), /5 MB/);
const target = { owner: 'test-owner', repo: 'blog', branch: 'master' };
let writes = 0;
const result = await uploadBlogImage(png, 'my-article', 'fake-test-token', target, async (url, options) => {
  writes++;
  assert.equal(options.method, 'PUT');
  assert.ok(url.startsWith('https://api.github.com/repos/test-owner/blog/contents/assets/images/posts/my-article/'));
  const body = JSON.parse(options.body), path = url.split('/contents/')[1];
  assert.equal(body.branch, 'master'); assert.equal(body.sha, undefined);
  assert.deepEqual(new Uint8Array(Buffer.from(body.content, 'base64')), png);
  assert.equal(body.message.includes('fake-test-token'), false);
  return new Response(JSON.stringify({ content: { path }, commit: { sha: 'a'.repeat(40) } }), { status: 201 });
});
assert.equal(writes, 1);
assert.equal(result.markdownUrl, '/' + result.path);
assert.match(result.previewUrl, /\/a{40}\/assets\/images/);
await assert.rejects(uploadBlogImage(png, '../unsafe', 'fake', target, async (url) => {
  assert.match(url, /\/posts\/notes\//);
  return new Response('{}', { status: 409 });
}), /未覆盖/);
await assert.rejects(uploadBlogImage(png, 'ok', '', target), /Token/);
await assert.rejects(uploadBlogImage(new TextEncoder().encode('<html>'), 'ok', 'fake', target), /仅支持/);
await assert.rejects(uploadBlogImage(png, 'ok', 'fake', target, async () => new Response('{}', { status: 401 })), /过期/);
console.log('Blog image upload and three-way block merge: PASS (mock GitHub only)');
