import assert from 'node:assert/strict';
import { buildRssReport, decodeRssBuffer, isPublicAddress, assertPublicFeedUrl, parseRssXml, validateRssSources } from './update-rss.mjs';
import { createRssSource, exportOpml, mergeRssReaderStates, parseOpml, parseRssReader, parseRssReport, parseRssSources, safeRssUrl } from '../src/lib/rss.ts';

const source = createRssSource('Example & docs', 'https://feeds.example.com/rss.xml');
assert.equal(source.id, createRssSource('Other name', source.url).id);
assert.deepEqual(parseRssSources({ version: 1, sources: [source] }), [source]);
assert.deepEqual(validateRssSources({ version: 1, sources: [source] }), [source]);
assert.throws(() => parseRssSources({ version: 1, sources: [source, source] }), /重复/);
assert.throws(() => validateRssSources({ version: 1, sources: Array(25).fill(source) }));
for (const url of ['javascript:alert(1)', 'file:///tmp/feed', 'http://localhost/rss', 'https://a.local/rss', 'http://127.0.0.1/rss', 'http://2130706433/rss', 'http://10.2.3.4/rss', 'http://172.20.1.2/rss', 'http://192.168.1.1/rss', 'http://169.254.169.254/rss', 'http://[::1]/rss', 'https://user:secret@feeds.example.com/rss', 'https://feeds.example.com:8080/rss', 'https://feeds.example.com\\foo']) {
  assert.equal(safeRssUrl(url), null, url);
  assert.throws(() => assertPublicFeedUrl(url), undefined, url);
}
for (const address of ['0.0.0.0', '127.0.0.1', '10.0.0.1', '100.64.0.1', '172.16.0.1', '192.168.0.1', '198.18.0.1', '169.254.169.254', '224.0.0.1', '192.0.2.1', '198.51.100.1', '203.0.113.1', '::', '::1', 'fc00::1', 'fe80::1', '::ffff:127.0.0.1', '2001:db8::1', '2002:7f00:1::1']) assert.equal(isPublicAddress(address), false, address);
assert.equal(isPublicAddress('1.1.1.1'), true);
assert.equal(isPublicAddress('2606:4700:4700::1111'), true);

const opml = exportOpml([source, createRssSource('中文 "阅读"', 'https://news.example.com/rss?a=1&b=2')]);
assert.deepEqual(parseOpml(opml).sources.map(item => item.url), [source.url, 'https://news.example.com/rss?a=1&b=2']);
assert.equal(parseOpml(opml).sources[0].title, source.title);
const imported = parseOpml(`<opml version="2.0"><body><outline text="Group"><outline text="one" xmlUrl="${source.url}"/><outline text="dup" xmlUrl="${source.url}"/><outline xmlUrl="http://localhost/rss"/></outline></body></opml>`);
assert.equal(imported.sources.length, 1);
assert.equal(imported.skipped, 2);
assert.throws(() => parseOpml('<!DOCTYPE opml SYSTEM "file:///etc/passwd"><opml></opml>'), /实体/);
assert.throws(() => parseOpml('<opml></opml>'), /没有可用/);

const rss = `<rss version="2.0"><channel><item><title><![CDATA[Hello &amp; world]]></title><link>https://news.example.com/one</link><pubDate>Sun, 27 Sep 2026 00:00:00 GMT</pubDate><description><![CDATA[<p>Good <b>news</b></p><script>alert(1)</script>]]></description></item><item><title>Duplicate</title><link>https://news.example.com/one</link></item><item><title>Unsafe</title><link>javascript:alert(1)</link></item><item><title>No title link</title><link>http://127.0.0.1/private</link></item></channel></rss>`;
const parsed = parseRssXml(rss, source);
assert.equal(decodeRssBuffer(Buffer.from('中文')), '中文');
assert.equal(decodeRssBuffer(Buffer.from([0xd6, 0xd0, 0xce, 0xc4]), 'text/xml; charset=gb2312'), '中文');
assert.throws(() => decodeRssBuffer(Buffer.from('x'), 'text/xml; charset=not-real'), /编码/);
assert.equal(parsed.length, 1);
assert.equal(parsed[0].title, 'Hello & world');
assert.equal(parsed[0].summary, 'Good news');
assert.equal(parsed[0].publishedAt, '2026-09-27T00:00:00.000Z');
const atom = `<feed xmlns="http://www.w3.org/2005/Atom"><entry><title>Atom</title><link rel="self" href="https://feeds.example.com/post.atom"/><link rel="alternate" href="/story"/><updated>2026-09-26T12:00:00Z</updated><summary>&lt;p&gt;Atom text&lt;/p&gt;</summary></entry></feed>`;
assert.equal(parseRssXml(atom, source)[0].url, 'https://feeds.example.com/story');
assert.equal(parseRssXml(atom, source)[0].summary, 'Atom text');
assert.throws(() => parseRssXml('<!DOCTYPE rss [<!ENTITY x SYSTEM "file:///etc/passwd">]><rss></rss>', source), /实体/);
assert.throws(() => parseRssXml('<html>Not a feed</html>', source), /不是 RSS/);
assert.throws(() => parseRssXml('<rss></rss>', source), /没有可用/);
assert.throws(() => parseRssXml('x'.repeat(1024 * 1024 + 1), source), /过大/);

const time1 = new Date('2026-09-27T01:00:00Z');
const time2 = new Date('2026-09-27T02:00:00Z');
const success = await buildRssReport([source], null, { fetcher: async () => rss, now: time1 });
assert.deepEqual(parseRssReport(success), success);
assert.equal(success.sources[0].fetchedAt, time1.toISOString());
const failed = await buildRssReport([source], success, { fetcher: async () => { throw new Error('HTTP 503'); }, now: time2 });
assert.deepEqual(failed.items, success.items);
assert.equal(failed.sources[0].fetchedAt, time1.toISOString());
assert.equal(failed.sources[0].error, 'HTTP 503');
assert.equal(failed.generatedAt, time2.toISOString());
assert.deepEqual(parseRssReport(failed), failed);
const switched = { ...source, url: 'https://other.example.com/rss' };
const switchedFailure = await buildRssReport([switched], success, { fetcher: async () => { throw new Error('HTTP 404'); }, now: time2 });
assert.equal(switchedFailure.items.length, 0);
assert.equal(switchedFailure.sources[0].fetchedAt, null);
const empty = await buildRssReport([], success);
assert.deepEqual(empty, { version: 1, generatedAt: null, sources: [], items: [] });
assert.deepEqual(parseRssReport(empty), empty);
const another = createRssSource('Other', 'https://other.example.com/rss');
const partial = await buildRssReport([source, another], success, { fetcher: async url => { if (url === source.url) throw new Error('timeout'); return atom; }, now: time2 });
assert.equal(partial.items.length, 2);
assert.ok(partial.sources[0].error);
assert.equal(partial.sources[1].error, undefined);
assert.equal(partial.sources[1].fetchedAt, time2.toISOString());
assert.throws(() => parseRssReport({ ...success, items: [...success.items, ...success.items] }), /无效/);
assert.throws(() => parseRssReport({ ...success, items: [{ ...success.items[0], url: 'javascript:alert(1)' }] }), /无效/);
const readerA = { version: 1, items: { a: { read: true, favorite: false, updatedAt: time1.toISOString() } } };
const readerB = { version: 1, items: { a: { read: true, favorite: true, updatedAt: time2.toISOString() }, b: { read: false, favorite: true, updatedAt: time1.toISOString() } } };
const merged = mergeRssReaderStates(readerA, readerB);
assert.equal(merged.items.a.favorite, true);
assert.equal(merged.items.b.favorite, true);
assert.deepEqual(mergeRssReaderStates(readerB, readerA), merged);
assert.deepEqual(mergeRssReaderStates(merged, readerA), merged);
assert.deepEqual(parseRssReader({ version: 1, items: { bad: { read: 'bad', favorite: false, updatedAt: 'bad' } } }).items, {});
console.log('rss self-check passed');
