import assert from 'node:assert/strict';
import { emptyStudyFeedback, feedbackContent, feedbackId, parseStudyFeedback, readStudyFeedback, reviewIntervalDays, saveStudyFeedback, mergeStudyFeedback, STUDY_FEEDBACK_KEY } from '../src/services/studyFeedback.ts';
import { captureSharedWorkspace, mergeSharedWorkspace, applySharedWorkspace } from '../src/services/workspaceSync.ts';
const memory = () => { const values = new Map(); return { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) }; };
const a = memory(), b = memory(), id = feedbackId('QUEST-001', 'S1');
const original = { answer: '自己的回答', observations: 'Network 观察', stuck: '缓存问题', confidence: 2 };
const start = new Date('2026-10-05T01:00:00Z');
assert.deepEqual(readStudyFeedback(a), emptyStudyFeedback());
assert.deepEqual([1, 2, 3].map(rating => reviewIntervalDays(rating, 0)), [1, 3, 7]);
assert.equal(reviewIntervalDays(3, 4), 30);
let saved = await saveStudyFeedback(id, original, null, 'save', a, start);
assert.equal(saved.nextReviewAt, null);
const schedule = await saveStudyFeedback(id, original, saved, 'schedule', a, start);
assert.equal(schedule.nextReviewAt, '2026-10-08T01:00:00.000Z');
assert.ok(schedule.updatedAt > saved.updatedAt);
await assert.rejects(saveStudyFeedback(id, { ...original, answer: 'stale' }, saved, 'save', a, start), /另一页面/);
saved = await saveStudyFeedback(id, { ...original, confidence: 3 }, schedule, 'review', a, start);
assert.equal(saved.reviewStage, 1);
assert.equal(saved.nextReviewAt, '2026-10-19T01:00:00.000Z');
const notClear = await saveStudyFeedback(id, { ...original, confidence: 1 }, saved, 'review', a, start);
assert.equal(notClear.reviewStage, 0);
assert.equal(notClear.nextReviewAt, '2026-10-06T01:00:00.000Z');
assert.throws(() => feedbackId('bad', 'S1'), /编号/);
assert.throws(() => parseStudyFeedback({ version: 2, entries: {} }), /格式/);
const raw = a.getItem(STUDY_FEEDBACK_KEY);
a.setItem(STUDY_FEEDBACK_KEY, '{broken');
assert.throws(() => readStudyFeedback(a), /原文未覆盖/);
await assert.rejects(saveStudyFeedback(id, original, null, 'save', a, start));
assert.equal(a.getItem(STUDY_FEEDBACK_KEY), '{broken');
a.setItem(STUDY_FEEDBACK_KEY, raw);
await assert.rejects(saveStudyFeedback(id, { ...original, answer: 'x'.repeat(8001) }, notClear, 'save', a, start), /8000/);
const quota = { getItem: a.getItem, setItem: () => { throw new DOMException('full', 'QuotaExceededError'); } };
await assert.rejects(saveStudyFeedback(id, original, notClear, 'save', quota, start), /full/);
assert.equal(a.getItem(STUDY_FEEDBACK_KEY), raw);
b.setItem(STUDY_FEEDBACK_KEY, raw);
const baseline = readStudyFeedback(a);
const left = await saveStudyFeedback(id, { ...original, answer: '电脑端的独立答案' }, notClear, 'save', a, start);
const right = await saveStudyFeedback(id, { ...original, answer: '手机端的独立答案' }, notClear, 'save', b, start);
const combined = mergeStudyFeedback(readStudyFeedback(a), readStudyFeedback(b), baseline);
assert.deepEqual(combined, mergeStudyFeedback(readStudyFeedback(b), readStudyFeedback(a), baseline));
assert.equal(combined.entries[id].alternatives.length, 1);
assert.deepEqual(new Set([combined.entries[id].answer, combined.entries[id].alternatives[0].answer]), new Set([left.answer, right.answer]));
assert.deepEqual(mergeStudyFeedback(readStudyFeedback(a), baseline, baseline), readStudyFeedback(a));
assert.deepEqual(mergeStudyFeedback(combined, combined), combined);
a.setItem(STUDY_FEEDBACK_KEY, JSON.stringify(combined));
await assert.rejects(saveStudyFeedback(id, original, combined.entries[id], 'save', a, start), /冲突副本/);
const resolved = await saveStudyFeedback(id, original, combined.entries[id], 'resolve', a, start);
assert.equal(resolved.alternatives.length, 0);
const source = captureSharedWorkspace(a, start), empty = { version: 1, entries: {}, history: {} };
assert.ok(mergeSharedWorkspace(source, empty).entries[STUDY_FEEDBACK_KEY]);
applySharedWorkspace(mergeSharedWorkspace(source, empty), b);
assert.deepEqual(readStudyFeedback(b), readStudyFeedback(a));
const good = { version: 1, entries: { [id]: { ...resolved, unknownSecret: 'not-exported' } } };
assert.equal(parseStudyFeedback(good).entries[id].unknownSecret, undefined);
assert.deepEqual(feedbackContent(resolved), original);
console.log('Study feedback, review scheduling, CAS, corrupt storage, sync conflict preservation: PASS');
