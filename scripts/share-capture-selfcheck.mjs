import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { buildCaptureBookmarklet, createShareInboxDraft, normalizeShareUrl, parseIncomingShare, parseShareFields, SHARE_LIMITS } from '../src/lib/shareCapture.ts';

const location = { pathname: '/nav/', search: '', hash: '#/' };
assert.equal(parseIncomingShare(location), null);
assert.equal(parseIncomingShare({ ...location, search: '?url=https://example.com' }), null);
const system = parseIncomingShare({ ...location, search: '?share_title=Hello&share_url=https%3A%2F%2Fexample.com&share_text=Note&theme=dark' });
assert.equal(system.source, 'system');
assert.deepEqual(system.fields, { title: 'Hello', url: 'https://example.com/', text: 'Note' });
assert.equal(system.cleanUrl, '/nav/?theme=dark#/');
assert.deepEqual(createShareInboxDraft(system.fields), { type: 'link', title: 'Hello', url: 'https://example.com/', content: 'Note', tags: ['网页收集'] });
const bookmark = parseIncomingShare({ ...location, hash: '#/capture?title=Docs&text=Selected&url=https%3A%2F%2Fexample.com%2Fa%3Fx%3D1' });
assert.equal(bookmark.source, 'bookmarklet');
assert.equal(bookmark.fields.url, 'https://example.com/a?x=1');
assert.equal(bookmark.cleanUrl, '/nav/#/');
const both = parseIncomingShare({ ...location, search: '?share_text=system', hash: '#/capture?text=bookmark' });
assert.equal(both.fields.text, 'bookmark');
assert.equal(both.cleanUrl, '/nav/#/');
assert.equal(parseIncomingShare({ ...location, search: '?capture=1&text=hello&keep=1' }).cleanUrl, '/nav/?keep=1#/');
assert.deepEqual(parseShareFields({ text: '阅读笔记\nhttps://example.com/page' }).fields, { title: '', url: 'https://example.com/page', text: '阅读笔记' });
assert.equal(parseShareFields({ url: 'https://example.com', text: 'https://example.com' }).fields.text, '');
for (const unsafe of ['javascript:alert(1)', 'data:text/html,hello', 'ftp://example.com', 'https://user:pass@example.com', 'https://example.com\\evil', 'https://example.com/\npath', '//example.com', 'https://example.com/' + 'x'.repeat(SHARE_LIMITS.url)]) {
  assert.equal(normalizeShareUrl(unsafe), null, unsafe);
  assert.throws(() => createShareInboxDraft({ title: '', text: '', url: unsafe }));
  const result = parseIncomingShare({ ...location, search: `?share_url=${encodeURIComponent(unsafe)}` });
  assert.equal(result.fields.url, '');
  assert.ok(result.warnings.length > 0);
  assert.equal(result.cleanUrl, '/nav/#/');
}
assert.equal(parseShareFields({ text: 'https://user:pass@example.com' }).fields.text, '');
assert.equal(parseShareFields({ text: 'javascript:alert(1)' }).fields.text, '');
const huge = parseShareFields({ title: '字'.repeat(500), text: '字'.repeat(20_000) });
assert.equal(huge.fields.title.length, SHARE_LIMITS.title);
assert.equal(huge.fields.text.length, SHARE_LIMITS.text);
assert.ok(huge.warnings.length > 0);
assert.equal(parseShareFields({ title: 'x'.repeat(239) + '🌟' }).fields.title.length, 239);
assert.throws(() => createShareInboxDraft({ title: 'x'.repeat(241), url: '', text: 'okay' }), /长度/);
assert.throws(() => createShareInboxDraft({ title: 'Only title', url: '', text: ' ' }), /网址或备注/);
assert.equal(parseIncomingShare({ ...location, search: '?share_title=OnlyTitle' }).warnings.at(-1), '没有可保存的网址或文本，请补充内容。');
assert.equal(parseIncomingShare({ ...location, search: '?share_text=' + 'a'.repeat(200_001) }).fields.text, '');
assert.equal(createShareInboxDraft({ title: '', url: '', text: 'Note' }).type, 'text');
const script = buildCaptureBookmarklet('https://example.com/nav/?token=secret#/admin');
assert.ok(script.startsWith('javascript:'));
assert.ok(script.includes('https://example.com/nav/'));
assert.ok(script.includes('#/capture?'));
assert.ok(!script.includes('token=secret'));
assert.ok(!script.includes('#/admin'));
assert.ok(script.includes('noopener,noreferrer'));
assert.throws(() => buildCaptureBookmarklet('javascript:alert(1)'));
const manifest = JSON.parse(await readFile(new URL('../public/manifest.webmanifest', import.meta.url), 'utf8'));
assert.deepEqual(manifest.share_target, { action: '/nav/', method: 'GET', params: { title: 'share_title', text: 'share_text', url: 'share_url' } });
console.log('share capture self-check passed');
